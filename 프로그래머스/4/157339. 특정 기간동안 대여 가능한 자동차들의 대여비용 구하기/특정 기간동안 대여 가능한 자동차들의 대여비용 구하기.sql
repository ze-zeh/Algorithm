SELECT C.CAR_ID, C.CAR_TYPE, (DAILY_FEE * 30) * (100 - DISCOUNT_RATE) / 100 AS FEE
FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY AS R
JOIN CAR_RENTAL_COMPANY_CAR AS C
ON R.CAR_ID = C.CAR_ID
JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN AS D
ON D.CAR_TYPE = C.CAR_TYPE AND DURATION_TYPE = '30일 이상'
WHERE C.CAR_TYPE IN ('세단', 'SUV')
    AND (DAILY_FEE * 30) * (100 - DISCOUNT_RATE) / 100 >= 500000
    AND (DAILY_FEE * 30) * (100 - DISCOUNT_RATE) / 100 < 2000000
GROUP BY C.CAR_ID
HAVING C.CAR_ID NOT IN (SELECT CAR_ID
                    FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
                    WHERE (START_DATE <= DATE('2022-11-30')
                         AND END_DATE >= DATE('2022-11-01'))
                        )
ORDER BY FEE DESC, C.CAR_TYPE, C.CAR_ID DESC

