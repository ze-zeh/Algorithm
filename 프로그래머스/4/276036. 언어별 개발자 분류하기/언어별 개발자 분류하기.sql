SELECT
    CASE
        WHEN D.SKILL_CODE & F.CODE
             AND D.SKILL_CODE & P.CODE THEN 'A'
        WHEN D.SKILL_CODE & C.CODE THEN 'B'
        WHEN D.SKILL_CODE & F.CODE THEN 'C'
    END AS GRADE,
    D.ID,
    D.EMAIL
FROM DEVELOPERS D
CROSS JOIN (
    SELECT SUM(CODE) AS CODE
    FROM SKILLCODES
    WHERE CATEGORY = 'Front End'
) AS F
CROSS JOIN (
    SELECT CODE
    FROM SKILLCODES
    WHERE NAME = 'Python'
) AS P
CROSS JOIN (
    SELECT CODE
    FROM SKILLCODES
    WHERE NAME = 'C#'
) AS C
WHERE
    D.SKILL_CODE & F.CODE OR D.SKILL_CODE & C.CODE
ORDER BY GRADE, D.ID;